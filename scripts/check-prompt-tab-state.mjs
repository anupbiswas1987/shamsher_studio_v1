import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import { CAMPAIGN_INITIAL_VALUES } from '../src/smart-campaign.js';
import { CALENDAR_DAY_INITIAL_VALUES } from '../src/calendar-day.js';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage();
  await page.goto(process.env.RENDER_UI_ORIGIN || 'http://127.0.0.1');
  await page.waitForSelector('#screen-tab-prompts');
  await page.click('#screen-tab-prompts');
  await page.waitForSelector('#campaign-english-tagline');
  const value = id => page.$eval(`#${id}`, e => e.value);
  const fill = async (id, text) => {
    await page.$eval(`#${id}`, (e, text) => {
      const proto = e instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype;
      Object.getOwnPropertyDescriptor(proto, 'value').set.call(e, text);
      e.dispatchEvent(new Event('input', { bubbles: true }));
    }, text);
  };
  const scene = async () => {
    await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Generate scene').click());
    await page.waitForSelector('#campaign-scene-prompt');
    return value('campaign-scene-prompt');
  };
  const tab = async name => { await page.click(`#prompt-tab-${name}`); await page.waitForSelector(name === 'calendar-day' ? '#calendar-day-date' : '#campaign-tagline-question'); };
  assert.equal(await value('campaign-english-tagline'), CAMPAIGN_INITIAL_VALUES.fixedEnglishTagline);
  assert.equal(await value('campaign-targeted-info'), '');
  assert.equal(await value('campaign-final-cta'), '');
  await page.click('.smart-campaign-check input');
  await fill('campaign-english-tagline', 'Smart custom English');
  await fill('campaign-fixed-intro', 'Smart custom intro');
  await fill('campaign-tagline-question', 'Smart custom headline');
  await fill('campaign-targeted-info', 'Smart custom message');
  await page.evaluate(() => document.querySelector('.smart-campaign-section').open = true);
  await fill('campaign-json-input', '{"smart":"saved"}');
  const smartScene = await scene();
  await tab('calendar-day');
  assert.equal(await value('campaign-english-tagline'), CALENDAR_DAY_INITIAL_VALUES.fixedEnglishTagline);
  assert.equal(await value('campaign-fixed-intro'), CALENDAR_DAY_INITIAL_VALUES.fixedIntro);
  assert.equal(await value('calendar-day-title-tagline'), '');
  assert.equal(await value('campaign-location-preset'), 'Custom Location');
  for (const id of ['campaign-location', 'campaign-crowd-details', 'campaign-people-type', 'campaign-scene-details', 'campaign-main-incident', 'campaign-shomser-action', 'campaign-supporting-reactions', 'campaign-director-notes']) assert.equal(await value(id), '');
  assert.equal(await value('campaign-json-input'), '');
  assert.equal(await value('campaign-targeted-info'), '');
  assert.equal(await value('campaign-final-cta'), '');
  assert.equal(await page.$eval('#campaign-english-tagline', e => e.disabled), true);
  await fill('calendar-day-date', '2026-11-13');
  await fill('calendar-day-occasion', 'World Kindness Day');
  const freshScene = await scene();
  assert.ok(freshScene.includes('Generate a suitable Bengali title_tagline, targetedInfo, and finalCta for each blank field'));
  await fill('calendar-day-title-tagline', 'Calendar custom headline');
  await fill('campaign-targeted-info', 'Calendar custom message');
  await page.click('.smart-campaign-check input');
  await fill('campaign-english-tagline', 'Calendar custom English');
  const calendarScene = await scene();
  await tab('smart-campaign');
  assert.equal(await value('campaign-english-tagline'), 'Smart custom English');
  assert.equal(await value('campaign-fixed-intro'), 'Smart custom intro');
  assert.equal(await value('campaign-tagline-question'), 'Smart custom headline');
  assert.equal(await value('campaign-targeted-info'), 'Smart custom message');
  assert.equal(await value('campaign-json-input'), '{"smart":"saved"}');
  assert.equal(await value('campaign-scene-prompt'), smartScene);
  assert.equal(await page.$eval('#campaign-english-tagline', e => e.disabled), false);
  await page.click('#prompt-tab-series-story');
  await tab('calendar-day');
  assert.equal(await value('calendar-day-date'), '2026-11-13');
  assert.equal(await value('calendar-day-occasion'), 'World Kindness Day');
  assert.equal(await value('calendar-day-title-tagline'), 'Calendar custom headline');
  assert.equal(await value('campaign-targeted-info'), 'Calendar custom message');
  assert.equal(await value('campaign-english-tagline'), 'Calendar custom English');
  assert.equal(await value('campaign-fixed-intro'), CALENDAR_DAY_INITIAL_VALUES.fixedIntro);
  assert.equal(await value('campaign-scene-prompt'), calendarScene);
  assert.equal(await value('campaign-json-input'), '');
  assert.equal(await page.$eval('#campaign-english-tagline', e => e.disabled), false);
  assert.equal((await page.$$('#campaign-targeted-info')).length, 1);
  console.log('Passed: independent defaults, fields, JSON inputs, generated prompts, unlock controls, and state across workflow switches.');
} finally { await browser.close(); }
