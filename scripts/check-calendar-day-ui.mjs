import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import { SMART_CAMPAIGN_DEFAULTS } from '../src/smart-campaign.js';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage();
  await page.goto(process.env.RENDER_UI_ORIGIN || 'http://127.0.0.1');
  await page.waitForSelector('#screen-tab-prompts');
  await page.click('#screen-tab-prompts');
  await page.waitForSelector('#prompt-tab-calendar-day');
  await page.click('#prompt-tab-calendar-day');
  await page.waitForSelector('#calendar-day-date');
  assert.equal(await page.$('#campaign-tagline-question'), null);
  await page.evaluate(defaults => {
    document.querySelector('.smart-campaign-section').open = true;
    const input = document.querySelector('#campaign-json-input');
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, JSON.stringify({ type: 'calendar-day', version: 1, values: { ...defaults, date: '2026-12-16', occasion: 'Victory Day', title_tagline: 'বিজয়ের আনন্দ সবার', targetedInfo: 'সবার পাশে দাঁড়ান', finalCta: 'আজ একটি ভালো কাজ করুন' } }));
    input.dispatchEvent(new Event('input', { bubbles: true }));
  }, SMART_CAMPAIGN_DEFAULTS);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Import campaign JSON' && !b.disabled));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Import campaign JSON').click());
  assert.equal(await page.$eval('#calendar-day-date', e => e.value), '2026-12-16');
  assert.equal(await page.$eval('#calendar-day-date', e => e.type), 'text');
  await page.click('[aria-label="Open calendar"]');
  await page.waitForSelector('#calendar-day-picker');
  await page.click('[aria-label="Previous month"]');
  await page.click('[aria-label="2026-11-13"]');
  assert.equal(await page.$eval('#calendar-day-date', e => e.value), '2026-11-13');
  assert.equal(await page.$('#calendar-day-picker'), null);
  await page.click('[aria-label="Open calendar"]');
  await page.keyboard.press('Escape');
  assert.equal(await page.$('#calendar-day-picker'), null);
  assert.equal(await page.$eval('[aria-label="Open calendar"]', e => e === document.activeElement), true);
  await page.click('[aria-label="Open calendar"]');
  await page.click('#calendar-day-occasion');
  assert.equal(await page.$('#calendar-day-picker'), null);

  assert.equal(await page.$eval('#calendar-day-occasion', e => e.value), 'Victory Day');
  assert.equal(await page.$eval('#calendar-day-title-tagline', e => e.value), 'বিজয়ের আনন্দ সবার');
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Generate image prompt' && !b.disabled));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Generate image prompt').click());
  await page.waitForSelector('#campaign-output-title');
  assert.ok(await page.evaluate(() => [...document.querySelectorAll('textarea')].some(e => e.value.includes('TITLE_TAGLINE\nবিজয়ের আনন্দ সবার') && e.value.includes('OCCASION\nVictory Day'))));
  await page.evaluate(() => {
    const input = document.querySelector('#calendar-day-title-tagline');
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, '');
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Generate scene').click());
  await page.waitForSelector('#campaign-scene-prompt');
  const scene = await page.$eval('#campaign-scene-prompt', e => e.value);
  assert.ok(scene.startsWith('# CALENDAR DAY STORY & SCENE GENERATOR'));
  assert.ok(scene.includes('KNOW — Learn Something'));
  assert.ok(scene.includes('Generate a suitable Bengali title_tagline'));
  assert.ok(scene.includes('"title_tagline"')); assert.ok(scene.includes('2026-11-13')); assert.ok(!scene.includes('taglineQuestion'));
  await page.evaluate(() => {
    const response = Object.fromEntries(['location', 'crowdDetails', 'peopleType', 'sceneDetails', 'mainIncident', 'shomserAction', 'supportingReactions', 'directorNotes'].map(key => [key, `Updated ${key}`]));
    Object.assign(response, { title_tagline: 'সবার পাশে থাকুন', targetedInfo: 'অন্যের কথা ভাবুন', finalCta: 'আজ ভালো কাজ করুন', fixedEnglishTagline: document.querySelector('#campaign-english-tagline').value, fixedIntro: document.querySelector('#campaign-fixed-intro').value });
    const input = document.querySelector('#campaign-scene-json');
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(input, JSON.stringify(response));
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Apply scene JSON' && !b.disabled));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent === 'Apply scene JSON').click());
  assert.equal(await page.$eval('#calendar-day-title-tagline', e => e.value), 'সবার পাশে থাকুন');
  assert.equal(await page.$eval('#campaign-targeted-info', e => e.value), 'অন্যের কথা ভাবুন');
  assert.equal(await page.$eval('#campaign-final-cta', e => e.value), 'আজ ভালো কাজ করুন');
  await page.setViewport({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow');
  await page.click('[aria-label="Open calendar"]');
  assert.ok(await page.$eval('#calendar-day-picker', e => { const r = e.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; }), 'Calendar popup outside mobile viewport');
  await page.click('[aria-label="Next month"]');
  await page.click('[aria-label="2026-12-16"]');
  assert.equal(await page.$eval('#calendar-day-date', e => e.value), '2026-12-16');
  await page.click('#prompt-tab-smart-campaign');
  await page.waitForSelector('#campaign-tagline-question');
  assert.equal(await page.$('#calendar-day-date'), null);
  console.log('Passed: Calendar Day tab, new fields, session import, image and scene prompts, mobile layout, Smart Campaign unchanged.');
} finally { await browser.close(); }
